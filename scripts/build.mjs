// Builds the installable, offline website into public/.
//   node scripts/build.mjs
// Source of truth for the page is umrah-companion.html (also published as a Claude artifact).
// This script swaps Google Fonts for the local copies in public/fonts, adds the PWA head tags,
// the install prompt, and writes a service worker that pre-caches every file.
import { readFile, writeFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const pub = path.join(root, "public");

let src = await readFile(path.join(root, "umrah-companion.html"), "utf8");
const title = (src.match(/<title>(.*?)<\/title>/) || [, "Labbayk Umrah Companion"])[1];
src = src
  .replace(/<title>.*?<\/title>\s*/, "")
  .replace(/<meta name="claude:[^>]*>\s*/g, "")
  .replace(/<link[^>]*fonts\.(googleapis|gstatic)\.com[^>]*>\s*/g, "");

const snippet = await readFile(path.join(root, "scripts/pwa-snippet.html"), "utf8");

const head = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>${title}</title>
<meta name="description" content="Umrah steps and duas in Arabic, Roman Urdu, Urdu and English, with repeat playback, a big-text practice mode and a Tawaf/Sa'i counter. Works offline.">
<meta name="theme-color" content="#0d0e0f">
<meta name="color-scheme" content="light dark">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Labbayk">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="32x32" href="icons/favicon-32.png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
<link rel="preload" href="fonts/ScheherazadeNew-400-arabic.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="fonts/fonts.css">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
</head>
<body>
`;
const html = head + src.trim() + "\n" + snippet + "\n</body>\n</html>\n";
await writeFile(path.join(pub, "index.html"), html);

// list every file to pre-cache
async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (!["sw.js", ".DS_Store"].includes(e.name)) out.push(p);
  }
  return out;
}
const files = (await walk(pub)).sort();
const hash = createHash("sha256");
for (const f of files) hash.update(await readFile(f));
const version = hash.digest("hex").slice(0, 10);
// Relative URLs, so the app works at a domain root (Netlify/Vercel) or in a subfolder (GitHub Pages).
const urls = ["./", ...files.map((f) => path.relative(pub, f).split(path.sep).join("/")).filter((u) => u !== "index.html")];

const sw = `// Generated by scripts/build.mjs. Do not edit by hand.
const VERSION = "${version}";
const CACHE = "labbayk-" + VERSION;
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const ROOT = new URL("./", self.location).href; // the app's own folder

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" })))));
});

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith("labbayk-") && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // external links (Nusuk etc.) go straight to the network

  // Pages: serve the cached app instantly, refresh the cache in the background.
  if (req.mode === "navigate") {
    e.respondWith((async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(ROOT);
      const network = fetch(req).then((r) => { if (r.ok) cache.put(ROOT, r.clone()); return r; }).catch(() => null);
      return cached || (await network) || new Response("Offline", { status: 503 });
    })());
    return;
  }

  // Fonts, icons, manifest: cache first.
  e.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const r = await fetch(req);
      if (r.ok) (await caches.open(CACHE)).put(req, r.clone());
      return r;
    } catch (err) {
      return new Response("", { status: 504 });
    }
  })());
});
`;
await writeFile(path.join(pub, "sw.js"), sw);
console.log(`Built public/ · ${urls.length} files pre-cached · version ${version}`);
